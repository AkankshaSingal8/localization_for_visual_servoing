#!/usr/bin/env python3
"""
Generate the three experiment trials files programmatically.

Every variable we care about is encoded in the per-trial ``tag`` string,
which the servo script writes into every CSV row. Post-hoc, the tag tells
us which object, which pose, which mode, which trial (and for robustness:
which condition). No paper notebook needed.

Run this once before the arm session:

    python experiments/generate_trials.py \\
        --depth-scale 0.00123 \\
        --fp-repo-dir /home/YOU/FoundationPose

It writes three YAML files into ./experiments/:
    - trials_main.yaml          (Experiment 1: 90 trials)
    - trials_robustness.yaml    (Experiment 2: 36 trials)
    - trials_qr_sweep.yaml      (Experiment 3: 16 trials)

You can then feed each to run_batch.py one at a time.
"""
import argparse
from pathlib import Path


# ── Experiment 1 configuration ────────────────────────────────────────

MAIN_OBJECTS = [
    ("cheezit",  "../masked_objects/cheez_it_box.png",     (0.19, 0.06, 0.22)),
    ("tissue",   "../masked_objects/amazon_tissue_box.png", (0.21, 0.07, 0.12)),
    ("cardboard","../masked_objects/cardboard_box.png",    (0.25, 0.15, 0.20)),
    ("protein",  "../masked_objects/protein_bar.png",      (0.16, 0.04, 0.05)),
    ("brownie",  "../masked_objects/brownie_box.png",      (0.18, 0.05, 0.20)),
]

# Start poses are named, not numerically defined — the operator physically
# places the object according to the name. The name ends up in the run tag
# so you can group by it after the fact.
MAIN_POSES = ["centered_far", "off_axis_left", "off_axis_high"]

MAIN_MODES = ["ibvs", "ekf", "foundationpose"]

MAIN_TRIALS_PER_CONDITION = 2


# ── Experiment 2 configuration ────────────────────────────────────────

ROBUSTNESS_OBJECT = ("cheezit",  "../masked_objects/cheez_it_box.png",
                     (0.19, 0.06, 0.22))

ROBUSTNESS_CONDITIONS = ["baseline", "occlusion", "dim_light", "distractor"]

ROBUSTNESS_TRIALS_PER_CONDITION = 3


# ── Experiment 3 configuration ────────────────────────────────────────

QR_OBJECT = ("cheezit",  "../masked_objects/cheez_it_box.png",
             (0.19, 0.06, 0.22))

QR_PROCESS_NOISE_POS = [0.005, 0.01, 0.02, 0.05]
QR_MEAS_NOISE_UV = [3.0, 6.0, 12.0, 24.0]


# ── YAML helpers ──────────────────────────────────────────────────────

def _dump_common(common: dict) -> str:
    lines = ["common:"]
    for k, v in common.items():
        if v is None:
            continue
        lines.append(f"    {k}: {v}")
    return "\n".join(lines)


def _dump_trial(trial: dict) -> str:
    lines = ["    - tag: " + trial["tag"]]
    for k, v in trial.items():
        if k == "tag":
            continue
        if v is None:
            continue
        if isinstance(v, list):
            vals = ", ".join(str(x) for x in v)
            lines.append(f"      {k}: [{vals}]")
        else:
            lines.append(f"      {k}: {v}")
    return "\n".join(lines)


def _write_yaml(path: Path, common: dict, trials: list):
    parts = [
        "# Auto-generated by experiments/generate_trials.py",
        "# Tag format encodes everything: <object>_<pose>_<mode>_<extra>_t<n>",
        "",
        _dump_common(common),
        "",
        "trials:",
    ]
    for t in trials:
        parts.append(_dump_trial(t))
        parts.append("")
    path.write_text("\n".join(parts))
    print(f"Wrote {path}  ({len(trials)} trials)")


# ── Experiment generators ─────────────────────────────────────────────

def gen_main(args) -> list:
    trials = []
    for obj_name, ref, box in MAIN_OBJECTS:
        for pose in MAIN_POSES:
            for mode in MAIN_MODES:
                for trial_n in range(1, MAIN_TRIALS_PER_CONDITION + 1):
                    tag = f"{obj_name}_{pose}_{mode}_t{trial_n}"
                    t = {
                        "tag": tag,
                        "mode": mode,
                        "reference": ref,
                    }
                    if mode == "foundationpose":
                        t["fp_box"] = list(box)
                    trials.append(t)
    return trials


def gen_robustness(args) -> list:
    obj_name, ref, box = ROBUSTNESS_OBJECT
    trials = []
    for cond in ROBUSTNESS_CONDITIONS:
        for mode in MAIN_MODES:
            for trial_n in range(1, ROBUSTNESS_TRIALS_PER_CONDITION + 1):
                tag = f"{obj_name}_{cond}_{mode}_t{trial_n}"
                t = {
                    "tag": tag,
                    "mode": mode,
                    "reference": ref,
                }
                if mode == "foundationpose":
                    t["fp_box"] = list(box)
                trials.append(t)
    return trials


def gen_qr_sweep(args) -> list:
    obj_name, ref, box = QR_OBJECT
    trials = []
    for q_pos in QR_PROCESS_NOISE_POS:
        for r_uv in QR_MEAS_NOISE_UV:
            # Encode Q/R in tag using readable-but-sortable format
            q_str = f"q{q_pos:.3f}".replace(".", "p")
            r_str = f"r{r_uv:g}".replace(".", "p")
            tag = f"{obj_name}_{q_str}_{r_str}_t1"
            trials.append({
                "tag": tag,
                "mode": "ekf",
                "reference": ref,
                "process_noise_pos": q_pos,
                "meas_noise_uv": r_uv,
            })
    return trials


# ── Main ──────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--depth-scale", type=float, default=None,
                    help="Persisted depth calibration scale (from a one-off "
                         "'c' calibration). Skips per-trial calibration.")
    ap.add_argument("--cam-to-robot", default="zed_forward",
                    choices=["identity", "zed_forward"])
    ap.add_argument("--fp-repo-dir", type=str, default=None,
                    help="Absolute path to the FoundationPose repo on the "
                         "GPU machine.")
    ap.add_argument("--out-dir", type=Path,
                    default=Path(__file__).resolve().parent,
                    help="Where to write the YAML files (default: "
                         "experiments/).")
    args = ap.parse_args()

    common = {
        "cam_to_robot": args.cam_to_robot,
        "depth_cal_m": 0.30,
    }
    if args.depth_scale is not None:
        common["depth_scale"] = args.depth_scale
    if args.fp_repo_dir is not None:
        common["fp_repo_dir"] = args.fp_repo_dir

    args.out_dir.mkdir(parents=True, exist_ok=True)

    _write_yaml(args.out_dir / "trials_main.yaml", common, gen_main(args))
    _write_yaml(args.out_dir / "trials_robustness.yaml", common,
                gen_robustness(args))
    _write_yaml(args.out_dir / "trials_qr_sweep.yaml", common,
                gen_qr_sweep(args))

    print("\nTag format reference:")
    print("  Experiment 1 (main):        <obj>_<pose>_<mode>_t<n>")
    print("  Experiment 2 (robustness):  <obj>_<condition>_<mode>_t<n>")
    print("  Experiment 3 (Q/R sweep):   <obj>_q<Q_pos>_r<R_uv>_t1")
    print("\nEverything between the first and last underscore maps to a "
          "category when you group by pipeline or condition post-hoc.")


if __name__ == "__main__":
    main()
