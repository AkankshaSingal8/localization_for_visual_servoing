#!/usr/bin/env python3
"""
Generate the per-pipeline three-way evaluation trials file.

Three experiments (one per pipeline), each with five object
subcomponents at the single P1 start pose, for 15 trials total.
Trials are ordered by pipeline so the operator runs one full
experiment (1 = IBVS, 2 = EKF+DINOv2, 3 = EKF+FoundationPose) before
switching pipelines.

Every variable we care about is encoded in the per-trial ``tag``
string, which the servo script writes into every CSV row. Post-hoc,
the tag tells us which object and which pipeline. No paper notebook
needed.

Run this once before the arm session:

    python experiments/generate_trials.py \\
        --depth-scale 0.00123 \\
        --fp-repo-dir /home/YOU/FoundationPose

It writes one YAML file into ./experiments/:
    - trials_main.yaml          (15 trials)

You can then feed it to run_batch.py.
"""
import argparse
from pathlib import Path


# ── Experiment configuration ──────────────────────────────────────────

MAIN_OBJECTS = [
    ("cheezit",  "../masked_objects/cheez_it_box.png",     (0.19, 0.06, 0.22)),
    ("tissue",   "../masked_objects/amazon_tissue_box.png", (0.21, 0.07, 0.12)),
    ("cardboard","../masked_objects/cardboard_box.png",    (0.25, 0.15, 0.20)),
    ("protein",  "../masked_objects/protein_bar.png",      (0.16, 0.04, 0.05)),
    ("brownie",  "../masked_objects/brownie_box.png",      (0.18, 0.05, 0.20)),
]

# All trials run from the single canonical start pose P1 (centered,
# ~50 cm). The pose is not encoded in the tag because there is only one.

# Pipelines are ordered ibvs -> ekf -> foundationpose so trials group
# into Experiment 1 (Pipeline A, IBVS), Experiment 2 (Pipeline B,
# EKF+DINOv2), and Experiment 3 (Pipeline C, EKF+FoundationPose).
MAIN_MODES = ["ibvs", "ekf", "foundationpose"]


# ── YAML helpers ──────────────────────────────────────────────────────

def _dump_common(common: dict) -> str:
    lines = ["common:"]
    for k, v in common.items():
        if v is None:
            continue
        lines.append(f"    {k}: {v}")
    return "\n".join(lines)


def _dump_trial(trial: dict) -> str:
    lines = ["    - tag: " + trial["tag"]]
    for k, v in trial.items():
        if k == "tag":
            continue
        if v is None:
            continue
        if isinstance(v, list):
            vals = ", ".join(str(x) for x in v)
            lines.append(f"      {k}: [{vals}]")
        else:
            lines.append(f"      {k}: {v}")
    return "\n".join(lines)


def _write_yaml(path: Path, common: dict, trials: list):
    parts = [
        "# Auto-generated by experiments/generate_trials.py",
        "# Tag format: <object>_<mode>  (single P1 pose, no repeats)",
        "# Trials are grouped by pipeline (Experiment 1, then 2, then 3).",
        "",
        _dump_common(common),
        "",
        "trials:",
    ]
    for t in trials:
        parts.append(_dump_trial(t))
        parts.append("")
    path.write_text("\n".join(parts))
    print(f"Wrote {path}  ({len(trials)} trials)")


# ── Trial generator ───────────────────────────────────────────────────

def gen_main(args) -> list:
    """
    Outer loop is pipeline (so all trials of Experiment 1 come first,
    then 2, then 3); inner loop is object. One trial per cell.
    """
    trials = []
    for mode in MAIN_MODES:
        for obj_name, ref, box in MAIN_OBJECTS:
            tag = f"{obj_name}_{mode}"
            t = {
                "tag": tag,
                "mode": mode,
                "reference": ref,
            }
            if mode == "foundationpose":
                t["fp_box"] = list(box)
            trials.append(t)
    return trials


# ── Main ──────────────────────────────────────────────────────────────

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--depth-scale", type=float, default=None,
                    help="Persisted depth calibration scale (from a one-off "
                         "'c' calibration). Skips per-trial calibration.")
    ap.add_argument("--cam-to-robot", default="zed_forward",
                    choices=["identity", "zed_forward"])
    ap.add_argument("--fp-repo-dir", type=str, default=None,
                    help="Absolute path to the FoundationPose repo on the "
                         "GPU machine.")
    ap.add_argument("--out-dir", type=Path,
                    default=Path(__file__).resolve().parent,
                    help="Where to write the YAML file (default: "
                         "experiments/).")
    args = ap.parse_args()

    common = {
        "cam_to_robot": args.cam_to_robot,
        "depth_cal_m": 0.30,
    }
    if args.depth_scale is not None:
        common["depth_scale"] = args.depth_scale
    if args.fp_repo_dir is not None:
        common["fp_repo_dir"] = args.fp_repo_dir

    args.out_dir.mkdir(parents=True, exist_ok=True)

    _write_yaml(args.out_dir / "trials_main.yaml", common, gen_main(args))

    print("\nTag format reference:")
    print("  <obj>_<mode>  (15 trials: 3 pipelines x 5 objects, single P1 pose)")
    print("\nGroup by the second field (mode) to get per-experiment aggregates.")


if __name__ == "__main__":
    main()
